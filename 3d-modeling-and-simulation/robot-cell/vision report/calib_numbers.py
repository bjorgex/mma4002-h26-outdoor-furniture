"""calib_numbers.tex for jig_vision_report.tex, from the newest tests/vision_lab/results/calib_*/report.json.
  python calib_numbers.py
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
runs = sorted((HERE.parent / "tests" / "vision_lab" / "results").glob("calib_*/report.json"))
r = json.loads(runs[-1].read_text())
i, h, f, j = r["intrinsics"], r["handeye"], r["fixed"], r["jigs"]
n_layouts = len({row["layout"] for row in j["rows"]})
vals = {
    "calibRun": runs[-1].parent.name,
    "calibLayouts": n_layouts,
    "calibRms": f"{i['rms_px']:.3f}",
    "calibFx": f"{abs(i['fx_err_pct']):.2f}",
    "calibHePos": f"{h['pos_err_mm']:.2f}",
    "calibHeRot": f"{h['rot_err_deg']:.2f}",
    "calibFixPos": f"{f['pos_err_mm']:.2f}",
    "calibFixRot": f"{f['rot_err_deg']:.2f}",
    "calibFixTable": f"{f.get('table_err_mm', float('nan')):.2f}",
    "calibHeTable": f"{h.get('table_err_mm', float('nan')):.2f}",
    "calibHeFound": ", ".join(f"{v:.2f}" for v in h["found_offset_mm"]),
    "calibCx": f"{max(abs(i['cx_err_px']), abs(i['cy_err_px'])):.1f}",
    "calibFound": j["found"],
    "calibMed": f"{j['err_marker_mm_median']:.2f}",
    "calibMax": f"{j['err_marker_mm_max']:.2f}",
    "calibFarMed": f"{j['err_100mm_away_mm_median']:.2f}",
    "calibFarMax": f"{j['err_100mm_away_mm_max']:.2f}",
    "calibRzMax": f"{j['rz_err_deg_max']:.2f}",
}
(HERE / "calib_numbers.tex").write_text(
    "% generated by calib_numbers.py from " + runs[-1].parent.name + "\n" +
    "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in vals.items()), encoding="utf-8")
print(vals)

"""Pictures + numbers for jig_vision_report.tex from the newest tests/vision_lab/results/walkthrough_*/ run
(sim_v10_walkthrough.py, or the sim's "Camera calibration" preset):  python walkthrough_figs.py [run folder]
  -> figures/wt_<step>.jpg, wt_numbers.tex (\\newcommand macros), wt_assembly.tex (one figure per assembly sheet)
"""
import json
import sys
from pathlib import Path

import cv2

HERE = Path(__file__).resolve().parent
if len(sys.argv) > 1:
    run = Path(sys.argv[1]).resolve()
else:
    run = sorted(p for p in (HERE.parent / "tests" / "vision_lab" / "results").glob("walkthrough_*")
                 if (p / "walkthrough.json").exists() and (p / "pics" / "s9_assembly_1.png").exists())[-1]
fig = HERE / "figures"
fig.mkdir(exist_ok=True)
for old in fig.glob("wt_*.jpg"):
    old.unlink()
for png in sorted((run / "pics").glob("s*.png")):
    img = cv2.imread(str(png))
    if img.shape[1] > 2400:                              # keep the PDF small
        img = cv2.resize(img, (2400, int(img.shape[0] * 2400 / img.shape[1])), interpolation=cv2.INTER_AREA)
    cv2.imwrite(str(fig / f"wt_{png.stem}.jpg"), img, [cv2.IMWRITE_JPEG_QUALITY, 85])
w = json.loads((run / "walkthrough.json").read_text())
c, m, e, t = w["calib"], w["measured"], w["measure_err_mm"], w["tip_err"]
coll = w.get("collisions", {})


def coll_txt(v):
    s = (Path(run) / f"collision_{v}.txt")
    if not s.exists():
        return "not checked"
    lines = s.read_text().splitlines()
    f = next((l.split(":", 1)[1].strip() for l in lines if l.startswith("fixtures:")), "?")
    p = next((l.split(":", 1)[1].strip() for l in lines if l.startswith("parts:")), "?")
    return f"fixtures {f}, parts {p}"


asm = w.get("assembly") or {}
vals = {"wtRun": run.name, "wtPhotos": w["calib_photos"], "wtRms": f"{c['rms_px']:.3f}",
        "wtHePos": f"{c['pos_err_mm']:.2f}", "wtHeFound": ", ".join(f"{v:.1f}" for v in c["found_offset_mm"]),
        "wtMeasMax": f"{max(e.values()):.2f}", "wtTipMax": f"{t['v10_max_mm']:.2f}", "wtTipMed": f"{t['v10_median_mm']:.2f}",
        "wtVnineMax": f"{t['v9_max_mm']:.0f}", "wtMoves": t["moves"],
        "wtCollNine": coll_txt("v9"), "wtCollTen": coll_txt("v10"),
        "wtAsmEvents": asm.get("events", "?") if isinstance(asm, dict) else "?",
        "wtAsmState": asm.get("state", "not run") if isinstance(asm, dict) else str(asm)}
for n, key in (("Base A", "A"), ("Base B", "B"), ("Plank rack", "R")):
    lx, ly, lr = (list(w["layout"][n]) + [0])[:3]
    vals[f"wtSet{key}"] = f"{lx:+d}/{ly:+d}\\,mm {lr:+d}\\,°"
    vals[f"wtGot{key}"] = f"{m[n]['x']:+.1f}/{m[n]['y']:+.1f}\\,mm {m[n]['rz']:+.1f}\\,°"
(HERE / "wt_numbers.tex").write_text("% generated by walkthrough_figs.py from " + run.name + "\n" +
                                     "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in vals.items()), encoding="utf-8")
sheets = sorted(fig.glob("wt_s9_assembly_*.jpg"))
(HERE / "wt_assembly.tex").write_text("".join(
    f"\\includegraphics[width=\\linewidth]{{figures/{s.name}}}\n"
    f"\\captionof{{figure}}{{V10 assembly, sheet {k} of {len(sheets)}: a picture at every grab and release.}}\n"
    + ("\\newpage\n" if k < len(sheets) else "") for k, s in enumerate(sheets, 1)), encoding="utf-8")
print(run.name, vals)
